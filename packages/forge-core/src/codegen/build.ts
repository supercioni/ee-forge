/**
 * Turns a project document into the three-file portable bundle
 * (ADR-0034 §3): content, map, and an EE-loadable scenario.
 *
 * Copy the three files into `<EE>/scripts/` and the scenario appears in
 * EmptyEpsilon's picker. Nothing in the install is modified.
 */

export interface BuildFile {
  readonly name: string;
  readonly contents: string;
  /**
   * Where the file belongs inside the EE install.
   *
   * - `scripts` — the portable bundle; copying is all that is required.
   * - `shiptemplates` — must sit in `scripts/shiptemplates/` AND be named in
   *   `shipTemplates.lua`, because EE only accepts `ShipTemplate()` during
   *   its launch-time template phase (ADR-0034 §3 correction).
   */
  readonly install: "scripts" | "shiptemplates";
}

export interface BuildResult {
  /** How the exodus-family actions were treated; see {@link BuildMode}. */
  readonly mode: BuildMode;
  readonly files: readonly BuildFile[];
  /** Non-fatal notes: references that may or may not exist in the install. */
  readonly warnings: readonly string[];
}

export interface BuildOptions {
  /** SHA-256 of the source document, stamped into each generated header. */
  readonly sourceHash: string;
  /** Scanned install, when available — enables reference checking. */
  readonly library?: EELibrary;
  /**
   * `vanilla` replaces every extension action with its recorded alternative
   * and needs nothing installed; `integrated` emits the extension's own code,
   * guarded by the alternatives. Default: integrated when a registered
   * extension owns an action the project uses, vanilla otherwise.
   */
  readonly mode?: BuildMode;
  /** Extensions available to an integrated build. */
  readonly extensions?: readonly ForgeExtension[];
}

const GENERATED_MARK = "GENERATED BY EE FORGE — DO NOT EDIT";

/**
 * Provenance banner.
 *
 * Deliberately colon-free: EE parses leading `-- Key: Value` comment lines
 * as scenario metadata and logs `Unknown scenario meta data: …` for every
 * one it does not recognise (observed 2026-08-09 with an earlier header
 * format). Keeping the banner free of `key: value` shapes keeps EE's log
 * clean.
 */
function header(project: EEProject, hash: string, role: string): string {
  return `-- ${GENERATED_MARK}
-- project ${project.id} (${role})
-- source  projects/${project.id}/project.json
-- sha256  ${hash}
-- target  ${project.eeVersion}
--
-- Edit the project document and build again. Hand edits here are
-- overwritten on the next build.`;
}

function luaGlobal(projectId: string): string {
  return `${projectId.replace(/-/g, "_")}_map`;
}

/**
 * Cross-reference checks Zod cannot express. Structural mistakes throw;
 * anything that merely *might* be provided by the EE install is a warning,
 * because a project can legitimately reference stock templates, factions,
 * textures and radar traces that this repo never sees.
 */
export function validateProject(
  project: EEProject,
  library?: EELibrary,
): string[] {
  const warnings: string[] = [];

  const groupIds = new Set<string>();
  for (const group of project.map.groups) {
    if (groupIds.has(group.id)) {
      throw new CodegenError(`duplicate map group id "${group.id}"`);
    }
    groupIds.add(group.id);
  }

  // Sectors are authoring organisation, never emitted — but a group filed under a sector that is not there (or two
  // sectors with one id) is a document the editor could not show correctly, so it is refused rather than exported.
  const sectorIds = new Set<string>();
  for (const sector of project.map.sectors) {
    if (sectorIds.has(sector.id)) {
      throw new CodegenError(`duplicate sector id "${sector.id}"`);
    }
    sectorIds.add(sector.id);
  }
  for (const item of [...project.map.groups, ...project.map.markers]) {
    if (typeof item.sector === "string" && !sectorIds.has(item.sector)) {
      throw new CodegenError(`"${item.id}" is filed under the sector "${item.sector}", which does not exist`);
    }
  }

  const markerIds = new Set<string>();
  for (const marker of project.map.markers) {
    if (markerIds.has(marker.id)) {
      throw new CodegenError(`duplicate marker id "${marker.id}"`);
    }
    markerIds.add(marker.id);
  }

  // A place naming a marker that was deleted (ADR-0038). The emitters would
  // catch it too — `placeResolver` throws on the way past — but this runs
  // before a single line is written and reports every broken reference at
  // once, instead of the first one the emitter happens to reach.
  const dangling = danglingMarkerIds(project);
  if (dangling.length > 0) {
    throw new CodegenError(
      `these markers are referenced but not defined: ${dangling
        .map((id) => `"${id}"`)
        .join(", ")}. Recreate the marker, or point the record at a literal position.`,
    );
  }

  // Sectors in play (ADR-0056): the same list the problem list shows. The first error stops the build; warnings ride with it.
  for (const issue of sectorIssues(project)) {
    if (issue.severity === "error") throw new CodegenError(issue.message);
    warnings.push(issue.message);
  }
  for (const issue of persistenceIssues(project)) {
    if (issue.severity === "error") throw new CodegenError(issue.message);
    warnings.push(issue.message);
  }

  // A ShipTemplate with no model kills EmptyEpsilon outright: it exits
  // during `shipTemplates.lua` with no Lua error and nothing in the log
  // (probed 2026-08-12 against the pinned install — exit code 5 with one
  // model-less template, a clean load with the same file once the template
  // named a model). A variant may inherit the model through copy(), so the
  // check walks the chain.
  const templatesByName = new Map(project.templates.map((t) => [t.name, t]));
  for (const template of project.templates) {
    const seen = new Set<string>();
    let current: EETemplateDef | undefined = template;
    let model: string | null = null;
    while (current !== undefined && !seen.has(current.name)) {
      seen.add(current.name);
      if (current.model !== null) {
        model = current.model;
        break;
      }
      current = current.copyOf === null ? undefined : templatesByName.get(current.copyOf);
    }
    if (model === null) {
      throw new CodegenError(
        `ship template "${template.name}" has no model. EmptyEpsilon quits while loading ` +
          `shipTemplates.lua when a template never calls setModel() — no Lua error, no log line. ` +
          `Give it a model, or copy a template that has one.`,
      );
    }
  }

  const objectIds = new Set<string>();
  for (const group of project.map.groups) {
    for (const object of group.objects) {
      if (objectIds.has(object.id)) {
        throw new CodegenError(`duplicate object id "${object.id}"`);
      }
      objectIds.add(object.id);
    }
  }

  // Dialogues (ADR-0039). Every reference is checked here rather than in
  // the emitter so a broken conversation is reported whole — an author
  // fixing one dead jump at a time, one build at a time, is the failure
  // mode this avoids.
  const dialogueIds = new Set<string>();
  for (const dialogue of project.logic.dialogues) {
    if (dialogueIds.has(dialogue.id)) {
      throw new CodegenError(`duplicate dialogue id "${dialogue.id}"`);
    }
    dialogueIds.add(dialogue.id);

    const nodeIds = new Set<string>();
    for (const node of dialogue.nodes) {
      if (nodeIds.has(node.id)) {
        throw new CodegenError(
          `dialogue "${dialogue.id}" has two nodes called "${node.id}"`,
        );
      }
      nodeIds.add(node.id);
    }
    if (!nodeIds.has(dialogue.entry)) {
      throw new CodegenError(
        `dialogue "${dialogue.id}" opens on node "${dialogue.entry}", which it does not define`,
      );
    }

    const brokenJumps = dialogue.nodes.flatMap((node) =>
      node.replies
        .filter((reply) => reply.target.kind === "node" && !nodeIds.has(reply.target.nodeId))
        .map((reply) => `${node.id} → ${(reply.target as { nodeId: string }).nodeId}`),
    );
    if (brokenJumps.length > 0) {
      throw new CodegenError(
        `dialogue "${dialogue.id}" jumps to nodes it does not define: ${brokenJumps.join(", ")}`,
      );
    }

    // Unreachable nodes are a warning, not an error: an author mid-edit
    // has every right to a node nothing points at yet.
    const reachable = new Set<string>([dialogue.entry]);
    const queue = [dialogue.entry];
    while (queue.length > 0) {
      // Shifted once, into a variable: `find` runs its predicate per node,
      // so calling shift() inside it drains the queue instead of reading
      // the head — and every node past the first hop looked unreachable.
      const nodeId = queue.shift();
      const current = dialogue.nodes.find((node) => node.id === nodeId);
      for (const reply of current?.replies ?? []) {
        if (reply.target.kind === "node" && !reachable.has(reply.target.nodeId)) {
          reachable.add(reply.target.nodeId);
          queue.push(reply.target.nodeId);
        }
      }
    }
    for (const node of dialogue.nodes) {
      if (!reachable.has(node.id)) {
        warnings.push(
          `dialogue "${dialogue.id}" node "${node.id}" is unreachable from "${dialogue.entry}"`,
        );
      }
    }
  }

  for (const group of project.map.groups) {
    for (const object of group.objects) {
      if (!("dialogueId" in object) || object.dialogueId === null) continue;
      if (!dialogueIds.has(object.dialogueId)) {
        throw new CodegenError(
          `object "${object.id}" answers with dialogue "${object.dialogueId}", which this project does not define`,
        );
      }
      // The stock service menu belongs to SpaceStation. Handing off to it
      // from anything else calls commsStationMainMenu on an object that has
      // no comms_data — EE's own script would be reading a station it was
      // never given.
      const dialogue = project.logic.dialogues.find((d) => d.id === object.dialogueId);
      const offersServices = dialogue?.nodes.some((node) =>
        node.replies.some((reply) => reply.target.kind === "services"),
      );
      if (offersServices === true && object.type !== "SpaceStation") {
        warnings.push(
          `object "${object.id}" is a ${object.type} but its dialogue "${object.dialogueId}" offers EE's station services — that menu expects a SpaceStation`,
        );
      }
    }
  }

  // Orbit targets must exist; the map emitter additionally orders parents
  // before satellites and rejects cycles.
  for (const group of project.map.groups) {
    for (const object of group.objects) {
      if (object.type === "Planet" && object.orbit !== null) {
        if (!objectIds.has(object.orbit.targetId)) {
          throw new CodegenError(
            `planet "${object.id}" orbits unknown object "${object.orbit.targetId}"`,
          );
        }
      }
    }
  }

  const projectFactions = new Set(project.factions.map((f) => f.name));
  const projectTemplates = new Set(project.templates.map((t) => t.name));
  const projectModels = new Set(project.models.map((m) => m.name));
  const libraryFactions = new Set(library?.factions.map((f) => f.name) ?? []);
  const libraryTemplates = new Set(library?.templates.map((t) => t.name) ?? []);
  const libraryModels = new Set(library?.models.map((m) => m.name) ?? []);

  const knownFaction = (name: string): boolean =>
    projectFactions.has(name) || libraryFactions.has(name);
  const knownTemplate = (name: string): boolean =>
    projectTemplates.has(name) || libraryTemplates.has(name);

  for (const group of project.map.groups) {
    for (const object of group.objects) {
      if ("faction" in object && !knownFaction(object.faction)) {
        warnings.push(
          library === undefined
            ? `object "${object.id}" uses faction "${object.faction}" — unverified (no install scan available)`
            : `object "${object.id}" uses faction "${object.faction}", which is neither defined by this project nor present in the scanned install`,
        );
      }
      if ("template" in object && !knownTemplate(object.template)) {
        warnings.push(
          library === undefined
            ? `object "${object.id}" uses template "${object.template}" — unverified (no install scan available)`
            : `object "${object.id}" uses template "${object.template}", which is neither defined by this project nor present in the scanned install`,
        );
      }
    }
  }

  for (const template of project.templates) {
    if (
      template.model !== null &&
      !projectModels.has(template.model) &&
      !libraryModels.has(template.model)
    ) {
      warnings.push(
        `template "${template.name}" uses model "${template.model}", which this project does not define${
          library === undefined ? " (no install scan available to confirm)" : " and the scanned install does not provide"
        }`,
      );
    }
  }

  for (const faction of project.factions) {
    for (const other of [...faction.enemies, ...faction.friends]) {
      if (!knownFaction(other)) {
        warnings.push(
          `faction "${faction.name}" references "${other}", which is neither defined by this project nor present in the scanned install`,
        );
      }
    }
  }

  const variableNames = new Set(project.logic.variables.map((v) => v.name));
  for (const rule of project.logic.rules) {
    for (const predicate of [rule.when, ...rule.conditions]) {
      if (
        (predicate.kind === "variable_equals" || predicate.kind === "variable_at_least") &&
        !variableNames.has(predicate.name)
      ) {
        warnings.push(
          `rule "${rule.id}" reads variable "${predicate.name}", which the project never declares`,
        );
      }
    }
  }

  return warnings;
}

function emitScenario(
  catalog: EECatalog,
  project: EEProject,
  hash: string,
  build: BuildContext,
): string {
  const mapGlobal = luaGlobal(project.id);
  const requires = [
    `require("${project.id}_content.lua")`,
    `require("${project.id}_map.lua")`,
  ];
  const names = runtimeNames(project.id);
  const context = { catalog, project, names };
  // Extensions that actually own an action here; the others add nothing.
  const active =
    build.mode === "integrated"
      ? build.extensions.filter((extension) =>
          extensionSites(project).some((site) => extension.owns(site.action)),
        )
      : [];
  // Only when a reply actually hands off to EE's stock station menu: the
  // load has a side effect (see stationServicesPrelude) and a project that
  // never uses it should not pay for it.
  if (usesStationServices(project)) requires.push(stationServicesPrelude());

  const persistence = usesPersistence(project);
  const rtName = names.rt;
  const initExtras = active.map((extension) => extension.initStatements(context)).join("");
  const updateExtras = [
    ...(persistence
      ? [`  if ${rtName}.persist.blocked_tick(delta) then return end\n`, `  ${rtName}.persist.advance(delta)\n`]
      : []),
    ...(usesSectorJumps(project) ? [`  ${mapGlobal}.watch_if_due(getScenarioTime())\n`] : []),
    ...(usesExodusSteps(project) ? [`  ${names.rt}.tick_steps(getScenarioTime())\n`] : []),
    ...active.map((extension) => extension.updateStatements(context)),
  ].join("");
  const preludes = active.map((extension) => extension.scenarioPrelude(context)).join("\n\n");

  // The EE header must be the first three lines of the file — without it
  // the scenario never appears in the new-game menu.
  return `-- Name: ${project.name}
-- Description: ${project.description.replace(/\s*\n\s*/g, " ")}
-- Type: Basic${persistence ? `
-- Setting[Campaign]: Whether this scenario saves the campaign (the state of every sector) and resumes it after EmptyEpsilon is closed
-- Campaign[Resume|Default]: Resume the latest saved campaign of this project, or start a new one if there is none
-- Campaign[New]: Start a new campaign (a saved campaign is never overwritten)
-- Campaign[Off]: Play without saving` : ""}
--
${header(project, hash, "scenario")}

${requires.join("\n")}

${emitLogic(catalog, project, build)}
${preludes === "" ? "" : `\n${preludes}\n`}
function init()
${initExtras}  ${persistence ? `${rtName}.persist.boot()` : `${mapGlobal}.spawn()`}${
    persistence
      ? `
  -- A resume that was refused starts nothing: the dialogues, relinks and GM buttons come with the campaign the crew chooses.
  if ${rtName}.persist.mode ~= "blocked" then
    ${rtName}.install_dialogues()
    ${rtName}.persist.relink_all()
    install_gm_buttons()
  end`
      : `
  ${luaGlobal(project.id).replace(/_map$/, "_rt")}.install_dialogues()
  install_gm_buttons()`
  }
end

function update(delta)
${updateExtras}  tick_beats(${persistence ? `${rtName}.persist.now()` : "getScenarioTime()"})
  tick_rules()
end
`;
}

/**
 * The project, the API catalog and the scanned library must describe one
 * engine. Building 2024 content against the 2026 catalog would validate
 * calls the target does not have; mixing libraries would accept templates
 * the target install never shipped.
 */
export function assertTargetsAgree(
  catalog: EECatalog,
  project: EEProject,
  library?: EELibrary,
): void {
  try {
    requireTarget(project.eeVersion);
  } catch (error) {
    throw new CodegenError(error instanceof Error ? error.message : String(error));
  }
  if (catalog.eeVersion !== project.eeVersion) {
    throw new CodegenError(
      `project "${project.id}" targets ${project.eeVersion} but the API catalog is for ${catalog.eeVersion}. ` +
        `Load the catalog of the project's target (loadCatalog("${project.eeVersion}")).`,
    );
  }
  if (library !== undefined && library.eeVersion !== project.eeVersion) {
    throw new CodegenError(
      `project "${project.id}" targets ${project.eeVersion} but the scanned library is from ${library.eeVersion}. ` +
        `Rescan the ${project.eeVersion} install, or build for the library's target.`,
    );
  }
}

export function buildProject(
  catalog: EECatalog,
  project: EEProject,
  options: BuildOptions,
): BuildResult {
  assertTargetsAgree(catalog, project, options.library);
  const warnings = validateProject(project, options.library);

  const extensions = options.extensions ?? [];
  const sites = extensionSites(project);
  const available = extensions.some((extension) => sites.some((site) => extension.owns(site.action)));
  const mode: BuildMode = options.mode ?? (sites.length > 0 && available ? "integrated" : "vanilla");
  if (mode === "integrated" && sites.length > 0 && !available) {
    throw new CodegenError(
      "this project uses EXODUS actions, but no EXODUS extension is registered for an integrated build — " +
        "register it, or export in vanilla mode",
    );
  }
  const stepCheck = validateExodusSteps(project, mode);
  if (stepCheck.errors.length > 0) throw new CodegenError(stepCheck.errors.join("\n"));
  warnings.push(...stepCheck.warnings);
  const build = makeBuildContext(mode, extensions);

  const files: BuildFile[] = [
    {
      name: `${project.id}_content.lua`,
      install: "scripts",
      contents: `${header(project, options.sourceHash, "content")}\n\n${emitContent(catalog, project)}`,
    },
    {
      name: `${project.id}_map.lua`,
      install: "scripts",
      contents: `${header(project, options.sourceHash, "map")}\n\n${emitMap(catalog, project)}`,
    },
    {
      name: `scenario_${project.id}.lua`,
      install: "scripts",
      contents: emitScenario(catalog, project, options.sourceHash, build),
    },
  ];

  // Models ride with the templates: both must exist before any scenario
  // runs, so a project with either needs the launch-time install step.
  if (project.templates.length > 0 || project.models.length > 0) {
    files.push({
      name: `${project.id}_templates.lua`,
      install: "shiptemplates",
      contents: `${header(project, options.sourceHash, "models + ship templates")}\n\n${emitTemplates(catalog, project)}`,
    });
  }

  return { mode, files, warnings };
}
