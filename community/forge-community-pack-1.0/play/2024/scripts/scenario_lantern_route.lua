--- Walk the scheduler. A "while" loop, not an "if": a long tick or an
--- unpause fires every beat it skipped, in order.
-- Campaign saves (ADR-0058): global beats run on the campaign clock; a beat scoped to a sector runs on that sector's own clock, only while it is active.
local gbeats, sbeats = {}, {}
for _, beat in ipairs(beats) do
  if beat.sector == nil then
    gbeats[#gbeats + 1] = beat
  else
    sbeats[beat.sector] = sbeats[beat.sector] or {}
    table.insert(sbeats[beat.sector], beat)
  end
end
local function tick_beats(t)
  while lantern_route_state.beat_idx <= #gbeats and t >= gbeats[lantern_route_state.beat_idx].at do
    local beat = gbeats[lantern_route_state.beat_idx]
    lantern_route_state.beat_idx = lantern_route_state.beat_idx + 1
    lantern_route_rt.run("beat " .. beat.id, beat.fn)
  end
  local sector = lantern_route_map.sector
  local list = sbeats[sector]
  if list ~= nil then
    local P = lantern_route_rt.persist
    local idx = P.sbeat[sector] or 1
    while idx <= #list and P.sector_now() >= list[idx].at do
      local beat = list[idx]
      idx = idx + 1
      P.sbeat[sector] = idx
      lantern_route_rt.run("beat " .. beat.id, beat.fn)
      -- a jump inside the beat changed the active sector: this list belongs to the one that was left
      if lantern_route_map.sector ~= sector then break end
      idx = P.sbeat[sector] or idx
    end
  end
end

local function tick_rules()
  local transitions = lantern_route_state.transitions
  for _, rule in ipairs(rules) do
    -- A jump happened in this update: the rules after it belong to the old sector. They wait for the next update, in the new world.
    if lantern_route_state.transitions ~= transitions then break end
    if not (rule.once and rule.fired) and (rule.sector == nil or rule.sector == lantern_route_map.sector) then
      local ok, value = pcall(rule.when)
      if ok then
        if value and not rule.was_true then
          lantern_route_rt.run("rule " .. rule.id, rule.fn)
          rule.fired = true
        end
        rule.was_true = value
      else
        print("[forge] rule " .. rule.id .. " predicate failed: " .. tostring(value))
      end
    end
  end
end

function init()
  lantern_route_rt.persist.boot()
  -- A resume that was refused starts nothing: the dialogues, relinks and GM buttons come with the campaign the crew chooses.
  if lantern_route_rt.persist.mode ~= "blocked" then
    lantern_route_rt.install_dialogues()
    lantern_route_rt.persist.relink_all()
    install_gm_buttons()
  end
end

function update(delta)
  if lantern_route_rt.persist.blocked_tick(delta) then return end
  lantern_route_rt.persist.advance(delta)
  lantern_route_map.watch_if_due(getScenarioTime())
  tick_beats(lantern_route_rt.persist.now())
  tick_rules()
end
